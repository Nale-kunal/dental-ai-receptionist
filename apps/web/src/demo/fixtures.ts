/**
 * Helper to produce an ISO string for a specific day offset from today and hour/minute in America/Chicago.
 */
function makeRelativeIso(baseDate: Date, dayOffset: number, hour: number, minute: number, timezone = 'America/Chicago'): string {
  const d = new Date(baseDate);
  d.setDate(d.getDate() + dayOffset);
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  const dateStr = `${year}-${month}-${day}`;
  const timeStr = `${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')}`;
  return toUtcIsoInTimezone(dateStr, timeStr, timezone);
}

function makeRelativeDateStr(baseDate: Date, dayOffset: number): string {
  const d = new Date(baseDate);
  d.setDate(d.getDate() + dayOffset);
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

